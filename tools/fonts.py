#!/usr/bin/env python3
"""Embed the u8g2 fonts the interface uses beyond the firmware's four, from the pinned
firmware's own u8g2 (tests/sim/fetch.sh puts it in build/sim/u8g2).

  tools/fonts.py [--check] [--u8g2 build/sim/u8g2/u8g2_fonts.c]

The firmware exports no font symbols to apps, so a FAP carries its own copy. app/ui/fonts.c is
written from FONTS: each u8g2 font array renamed to its role, byte for byte. `--check` fails
when the committed file differs from what the pinned source gives.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "ui" / "fonts.c"
FONTS = {"pocket_font_body": "u8g2_font_helvR08_tr"}


def extract(source, name):
    """(size, C string literal body) of one font array in u8g2_fonts.c."""
    head = re.search(r"const uint8_t " + re.escape(name) + r"\[(\d+)\][^\n]*=\n", source)
    if not head:
        raise SystemExit(f"fonts: {name} not found in the u8g2 source")
    end = source.index('";\n', head.end())
    return head.group(1), source[head.end():end + 1].strip()


def render(source):
    out = ["/* Generated by tools/fonts.py from the pinned firmware's u8g2 (lib/u8g2/u8g2_fonts.c);",
           " * do not edit. u8g2 is BSD-2-Clause; the X11 fonts it converts are freely usable. */",
           "/* clang-format off */", '#include "fonts.h"', ""]
    for role, name in FONTS.items():
        size, body = extract(source, name)
        out.append(f"/* {name} */")
        out.append(f"const uint8_t {role}[{size}] = {body};")
        out.append("")
    return "\n".join(out)


def main(argv):
    src = Path(argv[argv.index("--u8g2") + 1]) if "--u8g2" in argv else \
        ROOT / "build" / "sim" / "u8g2" / "u8g2_fonts.c"
    text = render(src.read_text(errors="replace"))
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("app/ui/fonts.c drifted from tools/fonts.py: run python3 tools/fonts.py",
                  file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
